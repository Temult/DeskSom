import {fixturePrefix} from './scripts/tests/fixture-paths.mjs';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createFastFileSearch,fastTool} from './fast-files.mjs';
const base=fs.mkdtempSync(fixturePrefix('native-index-mcp-test-'));
const root=path.join(base,'fixture'),state=path.join(base,'private-state'),db=path.join(state,'index.sqlite');
const config=path.join(base,'config.json');
if(!fs.statSync(base).isDirectory())throw Error('Unique fixture directory could not be created');
fs.mkdirSync(root,{recursive:true});fs.mkdirSync(state,{recursive:true});
const good=path.join(root,'match-native-mcp-707.txt');
fs.writeFileSync(good,'safe fixture');
fs.writeFileSync(config,JSON.stringify({schema:'desksom.index-v2/v1',root,database:db,allowedRoots:['C:\\Projects']}));
const runner=path.join(import.meta.dirname,'experiments','native-filename-index','index-v2.mjs');
const scan=spawnSync(process.execPath,[runner,'scan','--config',config],{encoding:'utf8',timeout:30000});
assert.equal(scan.status,0,scan.stderr);
const disabled=createFastFileSearch({stateDir:state,allowedDirectories:['C:\\Projects']});
assert.equal(disabled,null);
const serviceCfg={stateDir:state,allowedDirectories:[root],fastFilenameIndex:{enabled:true,indices:[{root,database:db}]}};
const fast=createFastFileSearch(serviceCfg);
assert.equal(fast.tool.name,'find_files_fast');assert.equal(fast.tool.annotations.readOnlyHint,true);
let result=(await fast.search({root,query:'native-mcp',limit:10})).structuredContent;
assert.equal(result.status,'INDEXED_RESULTS');assert.equal(result.results.length,1);
assert.equal(result.absenceAuthoritative,false);
result=(await fast.search({root,query:'definitely-unindexed-zzzz',limit:10})).structuredContent;
assert.equal(result.results.length,0);assert.equal(result.absenceAuthoritative,false);
result=(await fast.search({root:'C:\\Windows',query:'foo'})).structuredContent;
assert.equal(result.status,'ROOT_NOT_INDEXED');
result=(await fast.search({root,query:'foo',limit:999})).structuredContent;
assert.equal(result.status,'INVALID_QUERY');
assert.throws(()=>createFastFileSearch({stateDir:state,allowedDirectories:[root],fastFilenameIndex:{enabled:true,indices:[{root,database:'C:\\DL\\outside.sqlite'}]}}),/FAST_INDEX_DB_NOT_PRIVATE/);
assert.throws(()=>createFastFileSearch({stateDir:state,allowedDirectories:['C:\\DL'],fastFilenameIndex:{enabled:true,indices:[{root,database:db}]}}),/FAST_INDEX_ROOT_NOT_APPROVED/);
fs.unlinkSync(good);
fs.symlinkSync('C:\\Windows',good,'junction');
result=(await fast.search({root,query:'native-mcp'})).structuredContent;
assert.equal(result.results.length,0,'Cached redirected file path should never be exposed');
assert.equal(result.absenceAuthoritative,false);
const file=path.join(base,'MCP_TEST_RESULTS.json');
const receipt={status:'MCP_ADAPTER_PASS',noProductionChange:true,cases:9,fastSearchIsOptional:true,
  unchangedSourceRelease:true,verifiedPathsOnly:true};
fs.writeFileSync(file,JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(receipt));
